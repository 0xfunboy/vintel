import { cookies, headers } from "next/headers";

import type { Locale, Theme } from "./types";

export const locales: Locale[] = ["en", "it"];

export async function getLocalePreference(): Promise<Locale> {
  const cookieStore = await cookies();
  const cookieLocale = cookieStore.get("locale")?.value;
  if (cookieLocale === "en" || cookieLocale === "it") {
    return cookieLocale;
  }

  const acceptLanguage = (await headers()).get("accept-language") ?? "";
  return acceptLanguage.toLowerCase().startsWith("it") ? "it" : "en";
}

export async function getThemePreference(): Promise<Theme> {
  const cookieStore = await cookies();
  const cookieTheme = cookieStore.get("theme")?.value;
  return cookieTheme === "light" ? "light" : "dark";
}

export async function getCookieConsent() {
  const cookieStore = await cookies();
  return cookieStore.get("cookie_consent")?.value ?? null;
}

